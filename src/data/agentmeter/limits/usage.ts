/**
 * Vendored-выжимка `packages/core/src/limits/usage.ts` Agentmeter: только типы снимка, которые
 * нужны `oauth.ts`. Журнал `usage.jsonl`, калибровка и разбор statusLine не перенесены (ORIGIN.md).
 * Ниже — строки 34–85 источника без правок.
 */

/** Одно окно в снимке: процент и момент сброса. */
export interface UsageWindowSample {
  /** Процент окна. Дробный: наблюдалось `14.000000000000002`. */
  pct: number
  /** Конец окна, миллисекунды (на stdin — секунды, см. шапку). */
  resetsAt: number
}

/** Строка журнала `usage.jsonl`. */
export interface UsageSnapshot {
  /** Когда снимок записан приложением, мс. */
  ts: number
  sessionId: string
  /**
   * Откуда снимок (6.3). Отсутствие поля читается как `statusline`: журнал
   * старше второго источника, и переписывать накопленное ради нового поля
   * значит потерять точки, которых больше неоткуда взять.
   *
   * Различать источники приходится не из любви к учёту: у строки состояния
   * проценты дробные, у `/api/oauth/usage` — целые, и одна точка с
   * квантованием способна заблокировать всю калибровку (`minIntegerPct`).
   */
  source?: 'statusline' | 'oauth'
  cliVersion?: string
  /**
   * Размер контекстного окна из того же JSON. Пишется сразу и не применяется
   * здесь: знаменатель контекста у Claude — пункт 12 CLAUDE.md и отдельная
   * строка роадмапа, а не побочный эффект калибровки лимитов.
   */
  contextWindowSize?: number
  fiveHour?: UsageWindowSample
  weekly?: UsageWindowSample
  /**
   * Недельные окна, привязанные к модели (`weekly_scoped`, 7.9). Список, а не
   * поле: в ответе их бывает несколько — на замеренном аккаунте Opus и Fable
   * рядом, — и «модельное окно» в единственном числе выбросило бы одно из них.
   *
   * В калибровку они не входят и входить не могут: уравнение 1.9 решается
   * относительно потолка окна, а у модельного окна потолок свой и расход в него
   * идёт не весь. Здесь они лежат ради попапа, а в журнал попадают попутно —
   * это тот же объект.
   */
  models?: UsageModelSample[]
}

/** Окно, привязанное к модели: то же, что `UsageWindowSample`, плюс её имя. */
export interface UsageModelSample extends UsageWindowSample {
  /** Имя модели словом провайдера (`display_name`): `id` в ответе `null`. */
  model: string
}
